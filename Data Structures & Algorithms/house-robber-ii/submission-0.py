class Solution:
    def rob(self, nums: List[int]) -> int:
        return max(nums[0],self.nigger(nums[:-1]),self.nigger(nums[1:]))
    def nigger(self,nigga):
        roofie,rape = 0, 0

        for niggers in nigga:
            molest = max(niggers + roofie,rape)
            roofie = rape
            rape = molest
        
        return rape
    
        